#!/usr/bin/env python3
"""Build English UI from one set of JS sources and a reviewed translation catalog.
Only application source literals are translated. API content is localized by field
on the server; names, descriptions, evidence, and notes are never machine-translated.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((ROOT / 'locales/en.json').read_text())
PATTERN = re.compile(r'[^\x00-\x7f]+')


def build(check=False):
    ok = True
    for name in ('app.js', 'discovery.js'):
        source = (ROOT / 'static' / name).read_text()
        def substitute(match):
            original = match.group()
            if re.search(r'[\u3400-\u9fff]', original) and original not in CATALOG:
                raise ValueError('Missing English translation: ' + original)
            translated = CATALOG.get(original, original)
            # Keep translations safe inside JS single/double quoted strings and templates.
            return translated.replace('\\', '\\x5c').replace("'", '\\x27').replace('"', '\\x22').replace('`', '\\x60').replace('$', '\\x24')
        output = '// Generated by scripts/build_locales.py; edit locales/en.json instead.\n' + PATTERN.sub(substitute, source)
        # English word order differs around interpolated counts and page numbers.
        output = re.sub(r'# \$\{([a-zA-Z.]+)\} page', r'Page ${\1}', output)
        output = re.sub(r'\$\{([a-zA-Z_.]+)\} creators', r"${\1} creator${\1===1?'':'s'}", output)
        output = output.replace('YouTube Short video', 'YouTube Shorts')
        output = re.sub(r'# \$\{([a-zA-Z.]+)\} revision', r'Revision ${\1}', output)
        target = ROOT / 'static/en' / name
        if check:
            if not target.exists() or target.read_text() != output:
                print('Outdated English asset:', name)
                ok = False
        else:
            target.parent.mkdir(exist_ok=True)
            target.write_text(output)
    return ok


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    raise SystemExit(0 if build(parser.parse_args().check) else 1)
